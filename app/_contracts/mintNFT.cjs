const nftContract = new ethers.Contract(nftContractAddress, nftContractABI, wallet);
async function mintNFT(toAddress, tokenURI) {
    try {
        // Create the transaction object with gas parameters
        const tx = await nftContract.mintItem(toAddress, tokenURI, {
            maxFeePerGas: ethers.parseUnits('50', 'gwei'), // Set a higher fee
            maxPriorityFeePerGas: ethers.parseUnits('2', 'gwei') // Optional but can help prioritize
        });
        
        console.log('Minting NFT... Transaction Hash:', tx.hash);
        
        // Wait for the transaction to be confirmed
        await tx.wait();
        
        console.log('NFT Minted Successfully!');
    } catch (error) {
        console.error('Error minting NFT:', error);
    }
}



